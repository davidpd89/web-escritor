import fs from "node:fs/promises";
import path from "node:path";
import { fileURLToPath } from "node:url";

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");
const sourcePath = path.join(root, "data", "assistant-source-registry.json");
const targetPath = path.join(root, "assets", "assistant-source-registry.js");
const checkOnly = process.argv.includes("--check");

const registry = JSON.parse(await fs.readFile(sourcePath, "utf8"));
if (registry?.schema_version !== 1 || registry?.policy !== "deny-by-default" || !Array.isArray(registry.sources) || !registry.sources.length) {
  throw new Error("assistant source registry: invalid root contract");
}

const ids = new Set();
for (const source of registry.sources) {
  if (!source || typeof source.id !== "string" || !/^[a-z0-9][a-z0-9-]{0,80}$/i.test(source.id) || ids.has(source.id)) {
    throw new Error(`assistant source registry: invalid or duplicate id ${source?.id ?? "<missing>"}`);
  }
  if (source.visibility !== "public" || typeof source.url !== "string" || !/^\/(?!\/)[A-Za-z0-9_./-]*$/.test(source.url) || source.url.split("/").includes("..")) {
    throw new Error(`assistant source registry: unsafe source ${source.id}`);
  }
  if (typeof source.title !== "string" || !source.title.trim() || source.title.length > 180) {
    throw new Error(`assistant source registry: invalid title ${source.id}`);
  }
  ids.add(source.id);
}

const banner = "// AUTO-GENERATED by scripts/build-assistant-source-registry.mjs from data/assistant-source-registry.json.\n// Do not edit this file manually.\n";
const output = `${banner}export const ASSISTANT_SOURCE_REGISTRY = ${JSON.stringify(registry.sources, null, 2)};\n`;

if (checkOnly) {
  let current = "";
  try { current = await fs.readFile(targetPath, "utf8"); } catch {}
  if (current !== output) {
    console.error("assistant source registry generated artifact is stale; run: node scripts/build-assistant-source-registry.mjs");
    process.exit(1);
  }
  console.log(`assistant-source-registry: parity OK (${registry.sources.length} sources)`);
} else {
  await fs.writeFile(targetPath, output, "utf8");
  console.log(`assistant-source-registry: generated ${registry.sources.length} sources`);
}
