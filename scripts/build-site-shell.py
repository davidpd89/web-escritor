def footer_groups_with_extras(nav: dict, by_id: dict[str, Entry], extras: dict, rel_path: str) -> dict[str, list[Entry]]:
    groups: dict[str, list[Entry]] = {}
    for group_name, ids in nav.get("footer", {}).items():
        groups[group_name] = [by_id[item_id] for item_id in ids]

    for extra in extras.get("footerNavExtras", {}).values():
        if rel_path not in extra.get("pages", []):
            continue
        group = extra["group"]
        entry = by_id[extra["id"]]
        groups.setdefault(group, [])
        if entry.item_id not in {x.item_id for x in groups[group]}:
            groups[group].append(entry)
    return groups


