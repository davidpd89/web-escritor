def with_markers(block: str, start: str, end: str) -> str:
    return f"{start}\n{block}\n{end}"


def inline_script_hashes(text: str) -> list[str]:
    """sha256 CSP hash (base64) del contenido EXACTO de cada <script> inline
    ejecutable de esta pagina (speculationrules, config de GoatCounter,
    etc.). El hash de CSP es sensible a cada byte entre las etiquetas -- no
    se recorta ni se normaliza espacio en blanco, tiene que ser el
    contenido tal cual lo ve el navegador. Deduplicado y con orden estable
    para que el --check sea reproducible."""
    hashes: list[str] = []
    seen: set[str] = set()
    for match in INLINE_SCRIPT_RE.finditer(text):
        digest = hashlib.sha256(match.group(1).encode("utf-8")).digest()
        value = "sha256-" + base64.b64encode(digest).decode("ascii")
        if value not in seen:
            seen.add(value)
            hashes.append(value)
    return hashes


def apply_public_csp(text: str, rel_path: str) -> str:
    """Inserta/renueva el CSP publico del shell -- nunca toca un CSP que ya
    exista fuera de nuestros marcadores.

    Las herramientas de manuscrito llevan un `<meta http-equiv="Content-
    Security-Policy">` mas estricto escrito a mano (connect-src 'none'):
    ese caso entra por la segunda condicion (EXISTING_CSP_RE sin marcador) y
    se deja intacto a proposito. Solo las paginas que hoy no declaran ningun
    CSP reciben el generico de PUBLIC_CSP.
    """
    marker_pattern = re.compile(re.escape(CSP_START) + r"[\s\S]*?" + re.escape(CSP_END))

    policy = PUBLIC_CSP
    hashes = inline_script_hashes(text)
    if hashes:
        hash_list = " ".join(f"'{h}'" for h in hashes)
        policy = policy.replace(
            "script-src 'self' ", f"script-src 'self' {hash_list} "
        )
    generated = f'<meta http-equiv="Content-Security-Policy" content="{policy}">'
    wrapped = with_markers(generated, CSP_START, CSP_END)

    if marker_pattern.search(text):
        return marker_pattern.sub(wrapped, text, count=1)
    if EXISTING_CSP_RE.search(text):
        return text
    charset_match = CHARSET_RE.search(text)
    if not charset_match:
        raise BuildError(f"{rel_path}: no se encontró <meta charset> para insertar el CSP")
    insert_at = text.find("\n", charset_match.end())
    if insert_at == -1:
        insert_at = charset_match.end()
    return text[: insert_at + 1] + wrapped + "\n" + text[insert_at + 1 :]


def replace_or_insert_block(text: str, regex: re.Pattern[str], generated: str, start: str, end: str) -> tuple[str, bool]:
    marker_pattern = re.compile(re.escape(start) + r"[\s\S]*?" + re.escape(end))
    wrapped = with_markers(generated, start, end)
    if marker_pattern.search(text):
        return marker_pattern.sub(wrapped, text, count=1), True
    if regex.search(text):
        return regex.sub(wrapped, text, count=1), True
    return text, False


_SHELL_SOURCES: tuple[dict, dict[str, Entry], dict] | None = None


def shell_sources() -> tuple[dict, dict[str, Entry], dict]:
    """Carga (y memoiza) las tres fuentes del shell.

    Existe para que los builders que generan páginas —editoriales,
    convocatorias, temas del Cuaderno— puedan pedir el mismo shell que el resto
    del sitio sin releer los JSON en cada página.
    """
    global _SHELL_SOURCES
    if _SHELL_SOURCES is None:
        _SHELL_SOURCES = (load_json(NAV_PATH), ensure_registry(load_json(REGISTRY_PATH)), load_json(EXTRAS_PATH))
    return _SHELL_SOURCES


def inject_shell(text: str, rel_path: str) -> str:
    """Devuelve `text` con cabecera, Explorar y pie sustituidos por los del contrato.

    Es el punto de entrada para los builders de páginas. Antes cada uno llevaba
    su propia copia literal del shell en una cadena de Python: tres copias más
    que mantener a mano, y las tres se desincronizaron en cuanto el shell pasó a
    generarse. Ahora todos piden el mismo bloque a esta función, así que el
    `--check` de cada builder y el de este coinciden por construcción.
    """
    nav, by_id, extras = shell_sources()
    return apply_shell(text, rel_path, nav, by_id, extras)


def apply_shell(original: str, rel_path: str, nav: dict, by_id: dict[str, Entry], extras: dict) -> str:
    current_path = canonical_path_from_html(original) or ("/" if rel_path == "index.html" else "/" + rel_path.replace("index.html", ""))

    new_text = original
    header_html = render_header(nav, by_id, current_path)
    dialog_html = render_explore(nav, by_id, current_path)
    footer_html = render_footer(nav, by_id, extras, rel_path, current_path)

    new_text, ok_header = replace_or_insert_block(new_text, HEADER_RE, header_html, HEADER_START, HEADER_END)
    if not ok_header:
        raise BuildError(f"{rel_path}: no se encontró cabecera para inyectar shell")

    new_text, ok_dialog = replace_or_insert_block(new_text, DIALOG_RE, dialog_html, DIALOG_START, DIALOG_END)
    if not ok_dialog:
        pos = new_text.find(HEADER_END)
        if pos == -1:
            raise BuildError(f"{rel_path}: no se pudo insertar diálogo Explorar")
        insert_at = new_text.find("\n", pos)
        if insert_at == -1:
            insert_at = pos + len(HEADER_END)
        new_text = new_text[: insert_at + 1] + with_markers(dialog_html, DIALOG_START, DIALOG_END) + "\n\n" + new_text[insert_at + 1 :]

    new_text, ok_footer = replace_or_insert_block(new_text, FOOTER_RE, footer_html, FOOTER_START, FOOTER_END)
    if not ok_footer:
        raise BuildError(f"{rel_path}: no se encontró pie para inyectar shell")

    new_text = apply_public_csp(new_text, rel_path)

    return new_text


def process_page(path: Path, nav: dict, by_id: dict[str, Entry], extras: dict, check: bool) -> tuple[bool, bool]:
    original = path.read_text(encoding="utf-8", errors="replace")
    rel_path = path.relative_to(ROOT).as_posix()
    new_text = apply_shell(original, rel_path, nav, by_id, extras)

    changed = new_text != original
    if changed and not check:
        path.write_text(new_text, encoding="utf-8")
    return changed, check and changed


def main() -> int:
    parser = argparse.ArgumentParser()
    parser.add_argument("--check", action="store_true", help="No escribe; falla si hay páginas desactualizadas")
    args = parser.parse_args()

    nav = load_json(NAV_PATH)
    registry = ensure_registry(load_json(REGISTRY_PATH))
    extras = load_json(EXTRAS_PATH)

    pages, escapees = collect_shell_pages(ROOT)
    if not pages:
        raise BuildError("No se encontraron páginas shell")
    if escapees:
        raise BuildError(
            "páginas V1 sin shell y sin declarar en SHELL_EXEMPT: "
            + ", ".join(escapees)
            + " — o llevan el shell, o se declaran exentas con su motivo"
        )

    changed: list[str] = []
    for page in pages:
        page_changed, outdated = process_page(page, nav, registry, extras, check=args.check)
        if page_changed:
            changed.append(page.relative_to(ROOT).as_posix())
        if outdated:
            continue

    if args.check and changed:
        print("FAIL: shell desactualizado en:", file=sys.stderr)
        for item in changed:
            print(f" - {item}", file=sys.stderr)
        return 1

    mode = "CHECK" if args.check else "GENERATED"
    print(f"{mode}: shell en {len(pages)} páginas")
    if changed:
        print(f"CHANGED: {len(changed)}")
    return 0


if __name__ == "__main__":
    try:
        raise SystemExit(main())
    except BuildError as exc:
        print(f"FAIL: {exc}", file=sys.stderr)
        raise SystemExit(1)
