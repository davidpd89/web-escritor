# Cualquier <script> inline ejecutable: sin src (no es un fichero externo) y
# sin type="application/ld+json" (los navegadores probados no lo tratan como
# script ejecutable, asi que script-src nunca lo bloquea -- confirmado en el
# smoke test de esta PR: cero avisos de CSP sobre bloques ld+json en ninguna
