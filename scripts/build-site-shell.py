# confirmo que script-src lo bloquea igual que a JS normal.
INLINE_SCRIPT_RE = re.compile(
    r'<script(?![^>]*\bsrc=)(?![^>]*application/ld\+json)[^>]*>([\s\S]*?)</script>',
    re.I,
)

