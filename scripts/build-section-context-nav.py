ROOT = Path(__file__).resolve().parents[1]

NAV_START = "<!-- section-context:start (generated by scripts/build-section-context-nav.py -- do not edit by hand) -->"
NAV_END = "<!-- section-context:end -->"
HEADER_END_MARKER = "<!-- site-shell:header:end -->"

# This builder's own marker pair (regeneration case): both ends are exact
# literals, so the non-greedy middle can only ever match the single span
# between one specific start/end pair -- safe.
MARKER_PAIR_RE = re.compile(re.escape(NAV_START) + r"[\s\S]*?" + re.escape(NAV_END))
# The bare old, hand-authored PR#129 <nav class="section-context"> element
# itself, deliberately NOT trying to also swallow a preceding comment in the
# same regex -- an earlier version tried `(?:<!--[\s\S]*?-->\s*)?` in front
# of this and it backtracked across every unrelated "-->" in the whole
# document, from the first HTML comment in <head> through to this element,
# deleting everything in between. A stray preceding comment (each of the 5
# already-fixed pages worded its own by hand, no two alike) is instead
# stripped by strip_preceding_comment() below, which only ever looks at the
# single comment immediately adjacent to this match, never backtracks past
# an unrelated "-->" elsewhere in the file.
BARE_NAV_RE = re.compile(r"<nav class=\"section-context\"[\s\S]*?</nav>")


def strip_preceding_comment(text: str, start: int) -> int:
    before = text[:start]
    stripped = before.rstrip()
    if not stripped.endswith("-->"):
        return start
    comment_end = len(stripped)
    comment_start = before.rfind("<!--", 0, comment_end)
    if comment_start == -1:
        return start
    inner = before[comment_start + 4 : comment_end - 3]
    if "-->" in inner:
        return start  # more than one comment back-to-back -- leave alone
    return comment_start
CANONICAL_RE = re.compile(r'<link\s+[^>]*rel="canonical"[^>]*href="([^"]+)"', re.I)
HTML_TAG_RE = re.compile(r"<html\b[^>]*>", re.I)
V1_CLASS_RE = re.compile(r'\bclass="[^"]*\bv1\b')
EDITORIAL_CONTEXT_ATTR_RE = re.compile(r'\sdata-editorial-context="[^"]*"')


@dataclass(frozen=True)
class Context:
    key: str
    label: str
    home: str
    prefixes: tuple[str, ...]
    exacts: tuple[str, ...]
    links: tuple[tuple[str, str], ...]

    def matches(self, path: str) -> bool:
        return path in self.exacts or any(path.startswith(p) for p in self.prefixes)


