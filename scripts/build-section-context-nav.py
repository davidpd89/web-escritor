#!/usr/bin/env python3
"""Generate the pre-rendered `.section-context` local-nav strip.

`assets/v1-editorial-interior-v4.js`'s `buildContextNav()` inserts a
`<nav class="section-context">` right after `.site-header` on every V1 page
whose path matches one of its `contexts` entries -- a JS-after-paint
insertion that pushes `<main>` down without reserving its space first. #129
fixed this for 5 pages by hand-copying the JS's output into static HTML (the
script's own `document.querySelector('.section-context')` guard then makes
it a no-op there). This builder does the same thing for every page that
matches a context, generated instead of hand-copied, so it can cover all of
them at once and stay correct as pages are added.

CONTEXTS below mirrors the `contexts` array in
assets/v1-editorial-interior-v4.js by hand (same convention as that file's
own comment mirroring data/navigation.json's `localNavSets`) -- keep both in
sync when either changes. `qa/section-context-parity.mjs` diffs this
builder's output against what the JS actually generates, so drift between
the two fails CI instead of silently reappearing as CLS.

Follows the same marker + --check workflow as build-site-shell.py.
"""
from __future__ import annotations

