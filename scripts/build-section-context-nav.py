class BuildError(RuntimeError):
    pass


def normalise(path: str) -> str:
    path = re.sub(r"/index\.html$", "/", path)
    if len(path) > 1 and not path.endswith("/") and not path.lower().endswith(".html"):
        path += "/"
    return path


def find_context(current_path: str) -> Context | None:
    return next((c for c in CONTEXTS if c.matches(current_path)), None)


def score_links(context: Context, current_path: str) -> tuple[list[dict], dict | None]:
    scored = []
    for href, label in context.links:
        link_path = normalise(urlparse(href).path or href)
        exact = current_path == link_path
        family = (not exact) and link_path.endswith("/") and link_path != "/" and current_path.startswith(link_path)
        scored.append({"href": href, "label": label, "link_path": link_path, "exact": exact, "family": family})
    exact_match = next((s for s in scored if s["exact"]), None)
    best_family = None
    if not exact_match:
        candidates = [s for s in scored if s["family"]]
        if candidates:
            best_family = max(candidates, key=lambda s: len(s["link_path"]))
    return scored, exact_match or best_family


def render_nav(context: Context, current_path: str) -> str:
    scored, current_item = score_links(context, current_path)
    aria_current = ' aria-current="page"'
    links_html = "".join(
        f'<a href="{item["href"]}"{aria_current if item is current_item else ""}>{item["label"]}</a>'
        for item in scored
    )
    explanation = (
        "<!-- Pre-rendered to match assets/v1-editorial-interior-v4.js's buildContextNav()\n"
        "     output exactly (same classes/links/aria-current) for this page's context, so\n"
        "     it paints in its final position/size on first paint instead of being inserted\n"
        "     after the header post-load -- that JS insertion is a CLS source (see\n"
        "     docs/FINAL-CLOSURE-AUDIT-2026-08-27.md). The script's own\n"
        "     `document.querySelector('.section-context')` guard makes it a no-op once this\n"
        "     markup exists. Edit CONTEXTS in scripts/build-section-context-nav.py, not this\n"
        "     output; regenerate with `python scripts/build-section-context-nav.py`. -->"
    )
    nav = (
        f'<nav class="section-context" aria-label="Navegación de {context.label}" '
        f'data-editorial-context-nav="{context.key}"><div class="section-context__inner">'
        f'<a class="section-context__title" href="{context.home}">{context.label}</a>'
        f'<div class="section-context__links">{links_html}</div></div></nav>'
    )
    return f"{explanation}\n{nav}"


def canonical_path_from_html(text: str) -> str | None:
    match = CANONICAL_RE.search(text)
    if not match:
        return None
    return urlparse(match.group(1)).path or "/"


def tracked_html(root: Path) -> list[Path]:
    out = subprocess.run(
        ["git", "ls-files", "-z", "*.html"],
        cwd=root, capture_output=True, text=True, check=True,
    ).stdout
    return [root / rel for rel in out.split("\0") if rel]


def set_editorial_context_attr(html_tag: str, key: str) -> str:
    replacement = f'data-editorial-context="{key}"'
    if EDITORIAL_CONTEXT_ATTR_RE.search(html_tag):
        return EDITORIAL_CONTEXT_ATTR_RE.sub(f" {replacement}", html_tag, count=1)
    return html_tag[:-1] + f' {replacement}>' if html_tag.endswith(">") else html_tag


def apply_page(original: str, rel_path: str) -> str | None:
    """Returns the updated text, or None if this page isn't a V1 page with a
    context match (nothing to do -- not an error)."""
    html_match = HTML_TAG_RE.search(original)
    if not html_match or not V1_CLASS_RE.search(html_match.group(0)):
        return None

    current_path = normalise(canonical_path_from_html(original) or (
        "/" if rel_path == "index.html" else "/" + rel_path.replace("index.html", "")
    ))
    context = find_context(current_path)
    if context is None:
        return None
    if HEADER_END_MARKER not in original:
        raise BuildError(f"{rel_path}: matches context '{context.key}' but has no {HEADER_END_MARKER}")

    generated = render_nav(context, current_path)
    wrapped = f"{NAV_START}\n{generated}\n{NAV_END}"

    new_text = original
    marker_match = MARKER_PAIR_RE.search(new_text)
    bare_match = None if marker_match else BARE_NAV_RE.search(new_text)
    if marker_match:
        new_text = new_text[: marker_match.start()] + wrapped + new_text[marker_match.end() :]
    elif bare_match:
        replace_start = strip_preceding_comment(new_text, bare_match.start())
        new_text = new_text[:replace_start] + wrapped + new_text[bare_match.end() :]
    else:
        idx = new_text.find(HEADER_END_MARKER)
        insert_at = new_text.find("\n", idx)
        insert_at = insert_at + 1 if insert_at != -1 else idx + len(HEADER_END_MARKER)
        new_text = new_text[:insert_at] + "\n" + wrapped + "\n" + new_text[insert_at:]

    new_html_tag = set_editorial_context_attr(html_match.group(0), context.key)
    if new_html_tag != html_match.group(0):
        new_text = new_text.replace(html_match.group(0), new_html_tag, 1)

    return new_text


def main() -> int:
    parser = argparse.ArgumentParser()
    parser.add_argument("--check", action="store_true", help="No escribe; falla si hay páginas desactualizadas")
    args = parser.parse_args()

    changed: list[str] = []
    touched = 0
    for path in sorted(tracked_html(ROOT)):
        rel = path.relative_to(ROOT).as_posix()
        if rel.startswith("lab/"):
            continue
        original = path.read_text(encoding="utf-8", errors="replace")
        try:
            new_text = apply_page(original, rel)
        except BuildError as exc:
            print(f"FAIL: {exc}", file=sys.stderr)
            return 1
        if new_text is None:
            continue
        touched += 1
        if new_text != original:
            changed.append(rel)
            if not args.check:
                path.write_text(new_text, encoding="utf-8")

    if args.check and changed:
        print("FAIL: section-context desactualizado en:", file=sys.stderr)
        for item in changed:
            print(f" - {item}", file=sys.stderr)
        return 1

    mode = "CHECK" if args.check else "GENERATED"
    print(f"{mode}: section-context evaluado en {touched} páginas con contexto")
    if changed:
        print(f"CHANGED: {len(changed)}")
        for item in changed:
            print(f" - {item}")
    return 0


if __name__ == "__main__":
    try:
        raise SystemExit(main())
    except BuildError as exc:
        print(f"FAIL: {exc}", file=sys.stderr)
        raise SystemExit(1)
