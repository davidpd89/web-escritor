"""13/11: dos publicaciones seguidas cayeron en build-pagefind-index.py con

    npm error npx canceled due to missing packages and no YES option: ["pagefind@1.6.0"]

Pagefind subió de 1.5.2 a 1.6.0 en el lockfile de main (PR #1301, deriva npm) y el checkout
principal de este equipo se quedó con la instalación vieja. `link_node_modules` enlazaba
tree/node_modules al del checkout principal una sola vez y, si el enlace ya existía, no volvía
a mirarlo nunca: el desfase se quedaba para siempre aunque main avanzara.

Repositorios git reales (worktree real): el fallo es sobre cómo `git rev-parse --git-common-dir`
resuelve el checkout principal desde el árbol publicado, que un repo falso no reproduce igual.
"""
import importlib.util
import subprocess
import sys
import tempfile
import unittest
from pathlib import Path
from unittest.mock import patch

ROOT = Path(__file__).resolve().parents[1]


def load(name, rel):
    spec = importlib.util.spec_from_file_location(name, ROOT / rel)
    module = importlib.util.module_from_spec(spec)
    spec.loader.exec_module(module)
    return module


publisher = load('publisher_node_modules_sync', 'scripts/publish-reading-refresh.py')

OLD_LOCK = b'{"pagefind": "1.5.2 (pretend lockfile)"}'
NEW_LOCK = b'{"pagefind": "1.6.0 (pretend lockfile)"}'


def git(*args, cwd):
    subprocess.run(['git', *args], cwd=cwd, check=True, capture_output=True)


def init_repo(path, lock):
    path.mkdir(parents=True)
    (path / 'package-lock.json').write_bytes(lock)
    git('init', '-q', cwd=path)
    git('add', '.', cwd=path)
    git('-c', 'user.name=t', '-c', 'user.email=t@t', 'commit', '-q', '-m', 'x', cwd=path)


class NodeModulesSeDesincroniza(unittest.TestCase):
    def test_un_enlace_desfasado_del_checkout_principal_se_repara(self):
        """El enlace ya existe (como tras una ejecución anterior) pero apunta a un node_modules
        que no coincide con el lockfile de esta rama: debe repararse en vez de darse por bueno."""
        with tempfile.TemporaryDirectory() as tmp:
            principal = Path(tmp) / 'principal'
            init_repo(principal, OLD_LOCK)
            (principal / 'node_modules').mkdir()
            (principal / 'node_modules/.package-lock.json').write_bytes(OLD_LOCK)
            (principal / 'node_modules/pagefind-viejo').write_text('1.5.2', encoding='utf-8')

            tree = Path(tmp) / 'tree'
            git('worktree', 'add', '-q', '--detach', str(tree), cwd=principal)
            (tree / 'package-lock.json').write_bytes(NEW_LOCK)

            # Un día anterior, con los lockfiles en sincronía, se enlazó de verdad.
            if publisher.os.name == 'nt':
                subprocess.run(['cmd', '/c', 'mklink', '/J', str(tree / 'node_modules'), str(principal / 'node_modules')],
                                check=True, stdout=subprocess.DEVNULL)
            else:
                (tree / 'node_modules').symlink_to(principal / 'node_modules', target_is_directory=True)

            real_run = subprocess.run

            def run_o_simular_npm_ci(cmd, *args, **kwargs):
                if cmd == 'npm ci --no-audit --no-fund':
                    (tree / 'node_modules').mkdir(exist_ok=True)
                    (tree / 'node_modules/.package-lock.json').write_bytes(NEW_LOCK)
                    (tree / 'node_modules/pagefind-nuevo').write_text('1.6.0', encoding='utf-8')
                    return subprocess.CompletedProcess(cmd, 0)
                return real_run(cmd, *args, **kwargs)

            with patch.object(publisher.subprocess, 'run', side_effect=run_o_simular_npm_ci):
                publisher.link_node_modules(tree)

            self.assertTrue((tree / 'node_modules/pagefind-nuevo').exists(),
                             'el desfase con el lockfile de la rama debía repararse con una instalación propia')
            self.assertFalse((tree / 'node_modules/pagefind-viejo').exists(),
                              'no debe seguir enlazado al node_modules desfasado del checkout principal')

    def test_un_enlace_ya_sincronizado_no_se_toca(self):
        """Si lo que hay ya coincide con el lockfile de la rama (enlazado o propio), no hay que
        reinstalar ni relanzar npm cada vez que se publica."""
        with tempfile.TemporaryDirectory() as tmp:
            principal = Path(tmp) / 'principal'
            init_repo(principal, NEW_LOCK)
            (principal / 'node_modules').mkdir()
            (principal / 'node_modules/.package-lock.json').write_bytes(NEW_LOCK)

            tree = Path(tmp) / 'tree'
            git('worktree', 'add', '-q', '--detach', str(tree), cwd=principal)
            (tree / 'package-lock.json').write_bytes(NEW_LOCK)
            if publisher.os.name == 'nt':
                subprocess.run(['cmd', '/c', 'mklink', '/J', str(tree / 'node_modules'), str(principal / 'node_modules')],
                                check=True, stdout=subprocess.DEVNULL)
            else:
                (tree / 'node_modules').symlink_to(principal / 'node_modules', target_is_directory=True)

            with patch.object(publisher.subprocess, 'run') as mock_run:
                publisher.link_node_modules(tree)
            mock_run.assert_not_called()


if __name__ == '__main__':
    unittest.main()
